"""Independent SDXL adapter, called only inside a local offline-configured worker.

Imports are lazy. No model is selected, loaded or generated by importing this
module. The initial provider remains disabled pending real model integration tests.
"""

import gc
import importlib
import os
import secrets
import tempfile
import time
from pathlib import Path
from typing import Any

from stoneglass.inference.contracts import (
    GenerationRequest, GenerationResult, InferenceContext, ModelSpec, ModelVariant,
    ProgressEvent, ProgressStage, RuntimeDevice, RuntimeKind,
)
from stoneglass.inference.errors import ErrorCode, InferenceError
from stoneglass.inference.offline import OFFLINE_FLAGS, assert_offline_policy
from stoneglass.inference.resources import (
    SDXLManifest, ValidatedSDXL, invalid, read_manifest, strict_local, validate_sdxl,
)
from stoneglass.inference.validation import validate_request
from stoneglass.inference.resource_lease import ResourceLease


class ComponentValidationError(InferenceError):
    """Metadata-only diagnostics; strict loading still fails on every mismatch."""
    def __init__(self, report: dict[str, Any]) -> None:
        self.report = report
        super().__init__(ErrorCode.INVALID_RESOURCES,
                         "Checkpoint parameter names/shapes do not match the complete local SDXL component configurations. Nothing was downloaded.")


def _dependencies() -> Any:
    """Pinned internal conversion helpers must be re-reviewed on a version change."""
    from types import SimpleNamespace
    assert_offline_policy()
    torch = importlib.import_module("torch")
    diffusers = importlib.import_module("diffusers")
    transformers = importlib.import_module("transformers")
    if (str(torch.__version__) != "2.13.0+rocm10.0.0" or diffusers.__version__ != "0.40.0"
            or transformers.__version__ != "5.16.1"):
        raise InferenceError(ErrorCode.RUNTIME_UNAVAILABLE, "The worker requires the reviewed ROCm dependency profile.")
    return SimpleNamespace(torch=torch, diffusers=diffusers, transformers=transformers,
                           attention=importlib.import_module("diffusers.models.attention_processor"),
                           conversion=importlib.import_module("diffusers.loaders.single_file_utils"),
                           accelerate=importlib.import_module("accelerate"))


def validate_component_shapes(bundle: ValidatedSDXL, deps: Any) -> dict[str, Any]:
    """Validate *all* expected parameter shapes using metadata-only tensors.

    No checkpoint values are read by this conversion. Empty models live on the
    meta device; incomplete or differently configured components fail before
    from_single_file can attempt any model loading.
    """
    torch, diffusers, transformers, convert = deps.torch, deps.diffusers, deps.transformers, deps.conversion
    state = {name: torch.empty(spec.shape, device="meta", dtype=getattr(torch, {
        "F16": "float16", "BF16": "bfloat16", "F32": "float32", "I64": "int64",
        "I32": "int32", "BOOL": "bool",
    }[spec.dtype])) for name, spec in bundle.tensors.items()}
    try:
        with deps.accelerate.init_empty_weights():
            unet = diffusers.UNet2DConditionModel.from_config(bundle.configs["unet/config.json"])
            vae = diffusers.AutoencoderKL.from_config(bundle.configs["vae/config.json"])
            clip = transformers.CLIPTextModel(transformers.CLIPTextConfig.from_dict(bundle.configs["text_encoder/config.json"]))
            clip2 = transformers.CLIPTextModelWithProjection(transformers.CLIPTextConfig.from_dict(bundle.configs["text_encoder_2/config.json"]))
        components = (
            (unet, convert.convert_ldm_unet_checkpoint(state.copy(), bundle.configs["unet/config.json"])),
            (vae, convert.convert_ldm_vae_checkpoint(state.copy(), bundle.configs["vae/config.json"])),
            (clip, convert.convert_ldm_clip_checkpoint(state.copy())),
            (clip2, convert.convert_open_clip_checkpoint(clip2, state.copy(), prefix="conditioner.embedders.1.model.")),
        )
        report = {}
        for name, (model, converted) in zip(("unet", "vae", "clip_l", "clip_g"), components):
            # Older CLIP checkpoints may store this deterministic, nonpersistent buffer.
            converted.pop("text_model.embeddings.position_ids", None)
            # Match the pinned Diffusers create_diffusers_clip_model_from_ldm
            # normalization for Transformers 5's flattened CLIPTextModel.
            if name in ("clip_l", "clip_g") and not hasattr(model, "text_model"):
                converted = {key.removeprefix("text_model."): tensor for key, tensor in converted.items()}
            expected = {key: tuple(tensor.shape) for key, tensor in model.state_dict().items()}
            actual = {key: tuple(tensor.shape) for key, tensor in converted.items()}
            missing = sorted(set(expected) - set(actual))
            unexpected = sorted(set(actual) - set(expected))
            mismatched = sorted(key for key in set(expected) & set(actual) if expected[key] != actual[key])
            floating = all(tensor.is_floating_point() for tensor in converted.values())
            meta = all(tensor.is_meta for tensor in converted.values())
            report[name] = {"parameter_tensors": len(expected), "converted_tensors": len(actual),
                            "matched": actual == expected and floating and meta,
                            "missing_count": len(missing), "unexpected_count": len(unexpected),
                            "shape_mismatch_count": len(mismatched), "all_floating": floating,
                            "all_converted_tensors_meta": meta,
                            "missing_sample": missing[:5], "unexpected_sample": unexpected[:5],
                            "shape_mismatch_sample": mismatched[:5]}
        if any(not component["matched"] for component in report.values()):
            raise ComponentValidationError(report)
        return report
    except InferenceError:
        raise
    except Exception as exc:
        raise invalid(f"The checkpoint cannot be converted to the reviewed complete SDXL-base component layout ({type(exc).__name__}).") from None


class SDXLAdapter:
    """One pipeline in the owned process. Generation remains disabled in the application pending real integration tests."""

    def __init__(self, output_directory: Path) -> None:
        self._output = output_directory
        self._pipeline: Any = None
        self._deps: Any = None
        self._model: ModelSpec | None = None
        self._device: RuntimeDevice | None = None
        self._pending_output: Path | None = None
        self._measurements: dict[str, Any] = {}

    def diagnostics(self) -> dict[str, Any]:
        """Bounded local counters; never contains prompts, checkpoint paths or weights."""
        return dict(self._measurements)

    def load_model(self, model: ModelSpec, runtime: RuntimeDevice, context: InferenceContext) -> None:
        assert_offline_policy()
        if any(os.environ.get(k) != v for k, v in OFFLINE_FLAGS.items()):
            raise InferenceError(ErrorCode.OFFLINE_POLICY, "Required offline library policy is missing.")
        if model.architecture != "sdxl" or model.variant is not ModelVariant.BASE or model.adapters:
            raise invalid("The first SDXL adapter supports base checkpoints without additional adapters only.")
        if model.resource_manifest is None:
            raise invalid("Select a complete local SDXL resource manifest before loading.")
        if runtime.kind is not RuntimeKind.ROCM or type(runtime.index) is not int or runtime.index < 0:
            raise InferenceError(ErrorCode.RUNTIME_UNAVAILABLE, "This initial adapter requires the validated ROCm GPU profile.")
        manifest = read_manifest(model.resource_manifest)
        if manifest.checkpoint != strict_local(model.path):
            raise invalid("The manifest checkpoint does not match the selected model.")
        with ResourceLease(manifest):
            self._load_leased(model, runtime, context, manifest)

    def _load_leased(self, model: ModelSpec, runtime: RuntimeDevice, context: InferenceContext, manifest: SDXLManifest) -> None:
        started = time.monotonic()
        bundle = validate_sdxl(manifest, context)
        context.check_cancelled()
        context.report_event(ProgressEvent(ProgressStage.LOADING, 0, "Importing the reviewed local ROCm libraries; cold initialization may take several minutes"))
        self.unload()
        self._deps = _dependencies()
        self._device = runtime
        torch, diffusers = self._deps.torch, self._deps.diffusers
        if not torch.version.hip or torch.version.cuda is not None or not torch.cuda.is_available():
            raise InferenceError(ErrorCode.RUNTIME_UNAVAILABLE, "The selected ROCm device is not available in the worker.")
        properties = torch.cuda.get_device_properties(runtime.index)
        if "9060 XT" not in properties.name or getattr(properties, "gcnArchName", "") != "gfx1200":
            raise InferenceError(ErrorCode.RUNTIME_UNAVAILABLE, "This development profile has only validated the RX 9060 XT gfx1200.")
        context.check_cancelled()
        context.report_event(ProgressEvent(ProgressStage.VALIDATING, 0, "Checking all SDXL component parameter names and shapes on the meta device"))
        self._measurements["components"] = validate_component_shapes(bundle, self._deps)
        context.check_cancelled()
        context.report_event(ProgressEvent(ProgressStage.LOADING, 0, "Loading validated local SDXL weights; cancellation can terminate the owned worker"))
        with torch.cuda.device(runtime.index):
            torch.cuda.reset_peak_memory_stats(runtime.index)
            weights_started = time.monotonic()
            # The manifest supplies the complete config. HF flags provide library-level
            # offline behavior; this process is not an OS network sandbox.
            self._pipeline = diffusers.StableDiffusionXLPipeline.from_single_file(
                str(manifest.checkpoint), config=str(manifest.config_directory),
                local_files_only=True, token=False, dtype=torch.float16,
                use_safetensors=True, add_watermarker=False,
            )
            context.check_cancelled()
            # Explicit eager/math attention, including CLIP. No experimental fused paths.
            self._pipeline.unet.set_attn_processor(self._deps.attention.AttnProcessor())
            self._pipeline.vae.set_attn_processor(self._deps.attention.AttnProcessor())
            for encoder in (self._pipeline.text_encoder, self._pipeline.text_encoder_2):
                encoder.set_attn_implementation("eager")
            self._pipeline.to(runtime.torch_device)
            self._pipeline.set_progress_bar_config(disable=True)
            torch.cuda.synchronize(runtime.index)
        from stoneglass.inference.measurements import runtime_memory
        self._measurements["load"] = {"total_seconds": time.monotonic() - started,
            "weights_to_ready_seconds": time.monotonic() - weights_started,
            "memory": runtime_memory(torch, runtime.index)}
        context.check_cancelled()
        self._model, self._device = model, runtime

    def generate(self, request: GenerationRequest, context: InferenceContext) -> GenerationResult:
        assert_offline_policy()
        if any(os.environ.get(k) != v for k, v in OFFLINE_FLAGS.items()):
            raise InferenceError(ErrorCode.OFFLINE_POLICY, "Required offline library policy is missing.")
        if self._pipeline is None or self._model is None or self._device is None:
            raise InferenceError(ErrorCode.NOT_READY, "Load a validated local SDXL model first.")
        validate_request(request, self._model)
        settings = request.settings
        if settings.width * settings.height > 1024 * 1024:
            raise InferenceError(ErrorCode.INVALID_REQUEST, "The first SDXL profile permits at most 1,048,576 pixels at batch size one.")
        context.check_cancelled()
        seed = secrets.randbelow(2_147_483_648) if settings.seed == -1 else settings.seed
        torch = self._deps.torch
        started = time.monotonic()
        torch.cuda.reset_peak_memory_stats(self._device.index)

        def step(pipeline: Any, number: int, timestep: Any, tensors: dict[str, Any]) -> dict[str, Any]:
            context.check_cancelled()
            context.report_event(ProgressEvent(ProgressStage.GENERATING, (number + 1) * 100 // settings.steps,
                                                f"SDXL sampling step {number + 1} of {settings.steps}"))
            if number + 1 == settings.steps:
                context.report_event(ProgressEvent(ProgressStage.DECODING, 0, "Decoding the image with the local VAE"))
            return tensors

        with torch.inference_mode(), torch.cuda.device(self._device.index):
            generator = torch.Generator(device=self._device.torch_device).manual_seed(seed)
            response = self._pipeline(
                prompt=request.positive_prompt, negative_prompt=request.negative_prompt,
                width=settings.width, height=settings.height, num_inference_steps=settings.steps,
                guidance_scale=settings.guidance, num_images_per_prompt=1, generator=generator,
                callback_on_step_end=step, callback_on_step_end_tensor_inputs=[],
            )
            torch.cuda.synchronize(self._device.index)
        context.check_cancelled()
        if len(response.images) != 1 or response.images[0].size != (settings.width, settings.height):
            raise InferenceError(ErrorCode.GENERATION_FAILED, "SDXL returned an unexpected image count or dimensions.")
        image = response.images[0]
        from stoneglass.inference.measurements import runtime_memory
        self._measurements["generation"] = {"seconds": time.monotonic() - started,
            "memory": runtime_memory(torch, self._device.index)}
        output = strict_local(self._output, directory=True)
        context.report_event(ProgressEvent(ProgressStage.SAVING, 0, "Saving the full-resolution PNG locally"))
        # Only owned pending output is removed. The parent atomically moves this
        # file out of the private run directory at the service commit boundary.
        descriptor, temporary = tempfile.mkstemp(prefix="stoneglass-", suffix=".tmp", dir=output)
        pending = Path(temporary)
        final = pending.with_suffix(".png")
        try:
            with os.fdopen(descriptor, "wb") as stream:
                image.save(stream, format="PNG")
                stream.flush()
                os.fsync(stream.fileno())
            context.check_cancelled()
            os.replace(pending, final)
            self._pending_output = final
            context.report_event(ProgressEvent(ProgressStage.SAVING, 100, "Local PNG saved; validating output"))
        finally:
            pending.unlink(missing_ok=True)
        return GenerationResult(final, seed, settings.width, settings.height, self._model.model_id)

    def unload(self) -> None:
        device = self._device
        self._pipeline = None
        self._model, self._device = None, None
        if self._pending_output is not None:
            self._pending_output.unlink(missing_ok=True)
            self._pending_output = None
        gc.collect()
        if self._deps is not None:
            # Never let cancellation skip resource cleanup.
            torch = self._deps.torch
            if torch.cuda.is_available():
                with torch.cuda.device(device.index if device is not None else 0):
                    torch.cuda.empty_cache()
            if device is not None:
                from stoneglass.inference.measurements import runtime_memory
                self._measurements["unload"] = runtime_memory(torch, device.index)
